// Build @dataops/dsh-dataops-dev client face without a bundler.
//
// Same pattern as @dataops/dsh-dataops-client: the DSH browser host loads
// client plugins through window.__ModuleLoader__; React is provided by the
// host; sources are inlined in dependency order.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const read = path => readFileSync(join(root, path), 'utf8')
const write = (path, body) => {
  mkdirSync(dirname(join(root, path)), { recursive: true })
  writeFileSync(join(root, path), body)
}

const SOURCES = ['src/client/location.js', 'src/client/remote.js', 'src/client/view.js']

const inlined = SOURCES.map(path => {
  const body = read(path).replace(/^export\s+/mu, '')
  return `/* ---- ${path} ---- */\n${body}`
}).join('\n')

const index = read('src/client/index.js')

const client = `/* GENERATED by scripts/build.mjs - do not edit. Sources: ${SOURCES.join(', ')}, src/client/index.js */
window.__ModuleLoader__.load({
  id: "@dataops/dsh-dataops-dev",
  factory: (require) => {
    var module = { exports: {} }
    var exports = module.exports
    Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" })
    var React = require("react")

${inlined}

/* ---- src/client/index.js ---- */
${index}
    return module.exports
  }
})
`

write('lib/client.js', client)
console.log('built lib/client.js (%d bytes)', client.length)
