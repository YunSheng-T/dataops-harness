// Build @dataops/dsh-dataops-brand without a bundler.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const read = path => readFileSync(join(root, path), 'utf8')
const write = (path, body) => {
  mkdirSync(dirname(join(root, path)), { recursive: true })
  writeFileSync(join(root, path), body)
}

const brand = read('src/brand.js').replace(/^export\s+/mu, '')
const index = read('src/index.js').replace(/^export\s+/mu, '')
const host = read('src/host.js')

const client = `/* GENERATED by scripts/build.mjs - do not edit. Sources: src/brand.js, src/index.js */
window.__ModuleLoader__.load({
  id: "@dataops/dsh-dataops-brand",
  factory: (require) => {
    var module = { exports: {} }
    var exports = module.exports
    Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" })
    var React = require("react")

/* ---- src/brand.js ---- */
${brand}

    var Brand = createDataopsBrand(React)

/* ---- src/index.js ---- */
${index}
    return module.exports
  }
})
`

write('lib/client.js', client)
write('lib/index.js', host)

console.log('built lib/client.js (%d bytes) and lib/index.js (%d bytes)', client.length, host.length)
