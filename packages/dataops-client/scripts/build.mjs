// Build @dataops/dsh-dataops-client without a bundler.
//
// The DSH browser host loads client plugins through window.__ModuleLoader__, so
// a client package only needs a module that registers its factories. React is
// provided by the host; sources are inlined in dependency order.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const read = path => readFileSync(join(root, path), 'utf8')
const write = (path, body) => {
  mkdirSync(dirname(join(root, path)), { recursive: true })
  writeFileSync(join(root, path), body)
}

const SOURCES = [
  'src/stage-contract.generated.js',
  'src/cards.js',
  'src/flow.js',
  'src/stage-store.js',
  'src/context-store.js',
  'src/header-stage.js',
  'src/tabs.js',
  'src/brief.js',
  'src/document-preview.js'
]

function buildWorkbenchRuntime() {
  const dir = join(root, 'assets/lineage')
  const umd = readFileSync(join(dir, 'vendor/reactflow.umd.js'), 'utf8')
  const flowCss = readFileSync(join(dir, 'vendor/reactflow.css'), 'utf8')
  const workbenchCss = readFileSync(join(dir, 'workbench.css'), 'utf8')
  const overlayCss = [
    '.do-workbench-overlay{position:fixed;inset:0;z-index:95;background:#f7f7f8}',
    '.do-workbench-overlay .app{height:100%}',
    '.do-workbench-close-native{position:fixed;right:14px;top:12px;z-index:96;border:1px solid rgba(15,23,42,.12);background:#fff;color:#30343b;font:inherit;font-size:11px;line-height:26px;padding:0 10px;border-radius:6px;box-shadow:0 2px 8px rgba(15,23,42,.08);cursor:pointer}',
    '.do-workbench-close-native:hover{background:#f3f4f6}'
  ].join('')
  const icons = {}
  for (const file of ['apachehive', 'clickhouse', 'mysql', 'apachekafka', 'redis', 'apachespark', 'apacheairflow', 'db', 'job', 'api', 'report', 'schedule', 'bo', 'le']) {
    const svg = readFileSync(join(dir, 'vendor/icons', file + '.svg'))
    icons[file] = 'data:image/svg+xml;base64,' + svg.toString('base64')
  }
  icons.hive = icons.apachehive
  icons.kafka = icons.apachekafka
  icons.spark = icons.apachespark
  icons.airflow = icons.apacheairflow
  return [
    'var FLOW_CSS = ' + JSON.stringify(flowCss) + ';',
    'var FLOW_WORKBENCH_CSS = ' + JSON.stringify(workbenchCss + overlayCss) + ';',
    'var FLOW_ICONS = ' + JSON.stringify(icons) + ';',
    'var createReactFlowRuntime = function () {',
    '  var module = { exports: {} };',
    '  var exports = module.exports;',
    '  var requireShim = function (id) {',
    "    if (id === 'react') return React;",
    "    if (id === 'react-dom') return require('react-dom');",
    "    if (id === 'react/jsx-runtime') return { jsx: React.createElement, jsxs: React.createElement, Fragment: React.Fragment };",
    '    return require(id);',
    '  };',
    '  (function (module, exports, require) {',
    umd.replace(/<\/script/giu, '<\\/script'),
    '  })(module, exports, requireShim);',
    '  return module.exports;',
    '};'
  ].join('\n')
}

const WORKBENCH_RUNTIME = buildWorkbenchRuntime()

const inlined = SOURCES.map(path => {
  const body = read(path).replace(/^export\s+/mu, '')
  return `/* ---- ${path} ---- */\n${body}`
}).join('\n')

const index = read('src/index.js')
const host = read('src/host.js')

const client = `/* GENERATED by scripts/build.mjs - do not edit. Sources: ${SOURCES.join(', ')}, src/index.js */
window.__ModuleLoader__.load({
  id: "@dataops/dsh-dataops-client",
  factory: (require) => {
    var module = { exports: {} }
    var exports = module.exports
    Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" })
    var React = require("react")

${WORKBENCH_RUNTIME}
${inlined}

    var Cards = createDataopsCards(React)
    var StageStore = createStageStore()
    var HeaderStage = createHeaderStage(React, StageStore)
    var ContextStore = createContextStore()
    var LineageWorkbenchImpl = null
    var LineageFlow = {
      LineageWorkbench: function (props) {
        if (!props.open) return null
        if (!LineageWorkbenchImpl) LineageWorkbenchImpl = createLineageWorkbench(React, require('react-dom')).LineageWorkbench
        return React.createElement(LineageWorkbenchImpl, props)
      }
    }
    var Tabs = createDataopsTabs(React, ContextStore, LineageFlow)
    var Brief = createStageBrief(React, StageStore, ContextStore)
    var DataopsDocumentPreview = createDataopsDocumentPreview(React)

/* ---- src/index.js ---- */
${index}
    return module.exports
  }
})
`

write('lib/client.js', client)
write('lib/index.js', host)

console.log('built lib/client.js (%d bytes) and lib/index.js (%d bytes)', client.length, host.length)
