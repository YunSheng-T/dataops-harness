#!/usr/bin/env node
/** Generate the host/client mirrors from contracts/stage-contract.json. */
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const contract = JSON.parse(readFileSync(resolve(root, 'contracts/stage-contract.json'), 'utf8'))
const header = '/* GENERATED by scripts/sync-stage-contract.mjs - edit contracts/stage-contract.json. */\n'
const host = header
  + 'export const STAGES = ' + JSON.stringify(contract.storeStages) + '\n'
  + 'export const STAGE_KINDS = ' + JSON.stringify(contract.kinds, null, 2) + '\n'
  + 'export const GATE_ROLES = ' + JSON.stringify(contract.gates, null, 2) + '\n'
const client = header
  + 'var STAGE_CONTRACT = ' + JSON.stringify({
    uiStages: contract.uiStages,
    kinds: contract.kinds,
    uiKinds: contract.uiKinds,
    gates: contract.gates,
    stage6: contract.stage6
  }, null, 2) + ';\nif (typeof globalThis !== \'undefined\') globalThis.__DATAOPS_STAGE_CONTRACT = STAGE_CONTRACT;\n'
const targets = [
  [resolve(root, 'packages/dataops-tools/src/stage-contract.generated.js'), host],
  [resolve(root, 'packages/dataops-client/src/stage-contract.generated.js'), client]
]
const check = process.argv.includes('--check')
let changed = 0
for (const [path, body] of targets) {
  let current = ''
  try { current = readFileSync(path, 'utf8') } catch {}
  if (current !== body) {
    changed++
    if (!check) writeFileSync(path, body)
  }
}
if (check && changed) {
  console.error('stage contract generated files are stale; run node scripts/sync-stage-contract.mjs')
  process.exit(1)
}
console.log(check ? 'stage contract generated files: PASS' : 'stage contract generated files updated: ' + changed)
